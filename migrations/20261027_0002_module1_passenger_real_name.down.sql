-- ============================================================================
-- 模块1 用户账号与个人中心（成员A）—— 实名认证记录表（DOWN）
--
-- 回滚顺序：先删除认证记录表，再把乘客实名状态复位为「未认证」。
-- ⚠ 高风险操作：删除表会丢失已有认证数据，执行前必须备份并由组长确认。
-- ============================================================================

BEGIN;

DROP TABLE IF EXISTS passenger_real_name_records;

-- 认证记录已不存在，乘客侧状态同步复位，避免出现「认证中但无记录」的脏状态。
UPDATE passengers SET real_name_status = 0, updated_at = now() WHERE real_name_status = 1;

COMMIT;
